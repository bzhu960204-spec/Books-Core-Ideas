-- V7: Explanation marks - passages saved from a chapter's explanation (text + location).
--
-- Idempotent like earlier migrations: IF NOT EXISTS lets this no-op on databases
-- where Hibernate ddl-auto=update already created the table, while still applying
-- cleanly on databases that do not have it yet.

CREATE TABLE IF NOT EXISTS EXPLANATION_MARKS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOK_ID BIGINT NOT NULL,
    CHAPTER_ID BIGINT NOT NULL,
    QUOTE CLOB,
    PREFIX VARCHAR(200),
    SUFFIX VARCHAR(200),
    START_OFFSET INTEGER,
    END_OFFSET INTEGER,
    NOTE VARCHAR(1000),
    CREATED_AT TIMESTAMP,
    UPDATED_AT TIMESTAMP,
    CONSTRAINT FK_EXPL_MARK_BOOK FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(ID),
    CONSTRAINT FK_EXPL_MARK_CHAPTER FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS(ID)
);

CREATE INDEX IF NOT EXISTS IDX_EXPL_MARK_BOOK ON EXPLANATION_MARKS(BOOK_ID);
CREATE INDEX IF NOT EXISTS IDX_EXPL_MARK_CHAPTER ON EXPLANATION_MARKS(CHAPTER_ID);
