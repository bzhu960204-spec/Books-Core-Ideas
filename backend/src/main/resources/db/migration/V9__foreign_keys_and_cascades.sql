-- V9: Foreign keys and cascades (DB-02).
--
-- The database now keeps the data consistent on its own, not only through JPA:
--   * deleting an owner cascades to what it owns (ON DELETE CASCADE), as the JPA
--     cascades already do; the JPA cascades stay (they also run entity listeners);
--   * CHAPTER_IMAGES is the exception (ON DELETE RESTRICT): image files are removed
--     by a JPA entity listener, so a delete that bypasses JPA must not silently drop
--     image rows and leave their files behind;
--   * the membership and folder tables get the FKs they never had;
--   * child rows must have an owner (NOT NULL);
--   * READING_BOOKMARKS / EXPLANATION_MARKS store BOOK_ID next to CHAPTER_ID, and
--     CHAPTERS stores BOOK_ID next to PART_ID: composite FKs to (ID, BOOK_ID) make
--     sure those agree, so a row can never claim a different book than its parent.
--
-- H2 commits each DDL statement on its own, so the guards below check the data
-- first and abort before anything changes if a constraint could not be added.
-- (The alias keeps Flyway's log of the empty result from reading "aborted".)

-- ---- Guards: fail (data conversion error carrying the message) on violating data
SELECT CAST('V9 aborted: ' || CHECK_NAME || ' (' || N || ' rows)' AS INT) AS V9_CHECK_DATA
FROM (
    SELECT 'PARTS without book' AS CHECK_NAME, COUNT(*) AS N FROM PARTS WHERE BOOK_ID IS NULL
    UNION ALL SELECT 'CHAPTERS without book', COUNT(*) FROM CHAPTERS WHERE BOOK_ID IS NULL
    UNION ALL SELECT 'KEY_IDEAS without chapter', COUNT(*) FROM KEY_IDEAS WHERE CHAPTER_ID IS NULL
    UNION ALL SELECT 'EXCERPTS without chapter', COUNT(*) FROM EXCERPTS WHERE CHAPTER_ID IS NULL
    UNION ALL SELECT 'CHAPTER_IMAGES without chapter', COUNT(*) FROM CHAPTER_IMAGES WHERE CHAPTER_ID IS NULL
    UNION ALL SELECT 'BOOK_COLLECTION_ITEMS with missing book', COUNT(*) FROM BOOK_COLLECTION_ITEMS i
              WHERE NOT EXISTS (SELECT 1 FROM BOOKS b WHERE b.ID = i.BOOK_ID)
    UNION ALL SELECT 'BOOK_COLLECTION_ITEMS with missing collection', COUNT(*) FROM BOOK_COLLECTION_ITEMS i
              WHERE NOT EXISTS (SELECT 1 FROM BOOK_COLLECTIONS c WHERE c.ID = i.COLLECTION_ID)
    UNION ALL SELECT 'BOOK_COLLECTIONS with missing parent', COUNT(*) FROM BOOK_COLLECTIONS c
              WHERE c.PARENT_ID IS NOT NULL AND NOT EXISTS (SELECT 1 FROM BOOK_COLLECTIONS p WHERE p.ID = c.PARENT_ID)
    UNION ALL SELECT 'CHAPTERS in a part of another book', COUNT(*) FROM CHAPTERS c JOIN PARTS p ON p.ID = c.PART_ID
              WHERE p.BOOK_ID <> c.BOOK_ID
    UNION ALL SELECT 'READING_BOOKMARKS with a book other than their chapter''s', COUNT(*) FROM READING_BOOKMARKS r
              JOIN CHAPTERS c ON c.ID = r.CHAPTER_ID WHERE c.BOOK_ID <> r.BOOK_ID
    UNION ALL SELECT 'EXPLANATION_MARKS with a book other than their chapter''s', COUNT(*) FROM EXPLANATION_MARKS m
              JOIN CHAPTERS c ON c.ID = m.CHAPTER_ID WHERE c.BOOK_ID <> m.BOOK_ID
)
WHERE N > 0;

-- ---- 1. Drop the V8 foreign keys that change below
ALTER TABLE PARTS                DROP CONSTRAINT FK_PARTS_BOOK;
ALTER TABLE CHAPTERS             DROP CONSTRAINT FK_CHAPTERS_BOOK;
ALTER TABLE CHAPTERS             DROP CONSTRAINT FK_CHAPTERS_PART;
ALTER TABLE KEY_IDEAS            DROP CONSTRAINT FK_KEY_IDEAS_CHAPTER;
ALTER TABLE EXCERPTS             DROP CONSTRAINT FK_EXCERPTS_CHAPTER;
ALTER TABLE CHAPTER_IMAGES       DROP CONSTRAINT FK_CHAPTER_IMAGES_CHAPTER;
ALTER TABLE BOOK_REVIEWS         DROP CONSTRAINT FK_BOOK_REVIEWS_BOOK;
ALTER TABLE CHAPTER_EXPLANATIONS DROP CONSTRAINT FK_CHAPTER_EXPLANATIONS_CHAPTER;
ALTER TABLE READING_BOOKMARKS    DROP CONSTRAINT FK_READING_BOOKMARKS_BOOK;
ALTER TABLE READING_BOOKMARKS    DROP CONSTRAINT FK_READING_BOOKMARKS_CHAPTER;
ALTER TABLE EXPLANATION_MARKS    DROP CONSTRAINT FK_EXPLANATION_MARKS_BOOK;
ALTER TABLE EXPLANATION_MARKS    DROP CONSTRAINT FK_EXPLANATION_MARKS_CHAPTER;

-- ---- 2. Every child row has an owner
ALTER TABLE PARTS          ALTER COLUMN BOOK_ID    SET NOT NULL;
ALTER TABLE CHAPTERS       ALTER COLUMN BOOK_ID    SET NOT NULL;
ALTER TABLE KEY_IDEAS      ALTER COLUMN CHAPTER_ID SET NOT NULL;
ALTER TABLE EXCERPTS       ALTER COLUMN CHAPTER_ID SET NOT NULL;
ALTER TABLE CHAPTER_IMAGES ALTER COLUMN CHAPTER_ID SET NOT NULL;

-- ---- 3. Keys and indexes for the composite (…, BOOK_ID) foreign keys
ALTER TABLE PARTS    ADD CONSTRAINT UK_PARTS_ID_BOOK    UNIQUE (ID, BOOK_ID);
ALTER TABLE CHAPTERS ADD CONSTRAINT UK_CHAPTERS_ID_BOOK UNIQUE (ID, BOOK_ID);

DROP INDEX IDX_CHAPTERS_PART;
DROP INDEX IDX_READING_BOOKMARKS_CHAPTER;
DROP INDEX IDX_EXPLANATION_MARKS_CHAPTER;
CREATE INDEX IDX_CHAPTERS_PART_BOOK               ON CHAPTERS (PART_ID, BOOK_ID);
CREATE INDEX IDX_READING_BOOKMARKS_CHAPTER_BOOK   ON READING_BOOKMARKS (CHAPTER_ID, BOOK_ID);
CREATE INDEX IDX_EXPLANATION_MARKS_CHAPTER_BOOK   ON EXPLANATION_MARKS (CHAPTER_ID, BOOK_ID);
CREATE INDEX IDX_BOOK_COLLECTIONS_PARENT          ON BOOK_COLLECTIONS (PARENT_ID);

-- ---- 4. Foreign keys with their delete rules
ALTER TABLE PARTS ADD CONSTRAINT FK_PARTS_BOOK
    FOREIGN KEY (BOOK_ID) REFERENCES BOOKS (ID) ON DELETE CASCADE;
ALTER TABLE CHAPTERS ADD CONSTRAINT FK_CHAPTERS_BOOK
    FOREIGN KEY (BOOK_ID) REFERENCES BOOKS (ID) ON DELETE CASCADE;
-- A chapter's part must belong to the chapter's own book (no-op while PART_ID is NULL).
ALTER TABLE CHAPTERS ADD CONSTRAINT FK_CHAPTERS_PART
    FOREIGN KEY (PART_ID, BOOK_ID) REFERENCES PARTS (ID, BOOK_ID) ON DELETE CASCADE;
ALTER TABLE KEY_IDEAS ADD CONSTRAINT FK_KEY_IDEAS_CHAPTER
    FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID) ON DELETE CASCADE;
ALTER TABLE EXCERPTS ADD CONSTRAINT FK_EXCERPTS_CHAPTER
    FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID) ON DELETE CASCADE;
ALTER TABLE CHAPTER_EXPLANATIONS ADD CONSTRAINT FK_CHAPTER_EXPLANATIONS_CHAPTER
    FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID) ON DELETE CASCADE;
ALTER TABLE CHAPTER_IMAGES ADD CONSTRAINT FK_CHAPTER_IMAGES_CHAPTER
    FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID) ON DELETE RESTRICT;
ALTER TABLE BOOK_REVIEWS ADD CONSTRAINT FK_BOOK_REVIEWS_BOOK
    FOREIGN KEY (BOOK_ID) REFERENCES BOOKS (ID) ON DELETE CASCADE;
-- The chapter determines the book; the book itself is reached through the chapter.
ALTER TABLE READING_BOOKMARKS ADD CONSTRAINT FK_READING_BOOKMARKS_CHAPTER
    FOREIGN KEY (CHAPTER_ID, BOOK_ID) REFERENCES CHAPTERS (ID, BOOK_ID) ON DELETE CASCADE;
ALTER TABLE EXPLANATION_MARKS ADD CONSTRAINT FK_EXPLANATION_MARKS_CHAPTER
    FOREIGN KEY (CHAPTER_ID, BOOK_ID) REFERENCES CHAPTERS (ID, BOOK_ID) ON DELETE CASCADE;
ALTER TABLE BOOK_COLLECTION_ITEMS ADD CONSTRAINT FK_BOOK_COLLECTION_ITEMS_BOOK
    FOREIGN KEY (BOOK_ID) REFERENCES BOOKS (ID) ON DELETE CASCADE;
ALTER TABLE BOOK_COLLECTION_ITEMS ADD CONSTRAINT FK_BOOK_COLLECTION_ITEMS_COLLECTION
    FOREIGN KEY (COLLECTION_ID) REFERENCES BOOK_COLLECTIONS (ID) ON DELETE CASCADE;
ALTER TABLE BOOK_COLLECTIONS ADD CONSTRAINT FK_BOOK_COLLECTIONS_PARENT
    FOREIGN KEY (PARENT_ID) REFERENCES BOOK_COLLECTIONS (ID) ON DELETE CASCADE;
