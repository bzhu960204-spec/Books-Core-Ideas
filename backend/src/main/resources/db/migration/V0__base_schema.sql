-- V0: Base schema for a brand-new (empty) database.
--
-- V1..V7 were written as patches on top of a schema originally created by
-- Hibernate (ddl-auto=update), so on an empty database they failed: Flyway runs
-- before Hibernate and e.g. V2 updates BOOKS before it exists.
--
-- This script creates the core tables those patches depend on, in their current
-- shape. Constraint names match what Hibernate generates, so fresh and legacy
-- databases end up equivalent.
--
-- Existing databases were adopted with spring.flyway.baseline-version=0, so this
-- version is at/below their baseline and Flyway skips it there. Tables created
-- by later migrations (CHAPTER_EXPLANATIONS, BOOK_COLLECTIONS,
-- BOOK_COLLECTION_ITEMS, READING_BOOKMARKS, EXPLANATION_MARKS) are left to them.

CREATE TABLE IF NOT EXISTS BOOKS (
    ID                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE                  VARCHAR(255),
    AUTHOR                 VARCHAR(255),
    ISBN                   VARCHAR(255),
    DESCRIPTION            VARCHAR(2000),
    COVER_URL              VARCHAR(255),
    DATE_ADDED             DATE,
    RATING                 INTEGER,
    CATEGORY               VARCHAR(255),
    READING_STATUS         VARCHAR(255),
    START_DATE             DATE,
    FINISH_DATE            DATE,
    CHAPTER_IMAGES_ENABLED BOOLEAN DEFAULT FALSE,
    STRUCTURE_TYPE         VARCHAR(20) DEFAULT 'CHAPTERS'
);

CREATE TABLE IF NOT EXISTS PARTS (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE       VARCHAR(255),
    ORDER_INDEX INTEGER,
    SUMMARY     VARCHAR(1000),
    BOOK_ID     BIGINT,
    CONSTRAINT FKM12UEOT8L288S8PIHP2F3SNJJ FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(ID)
);

CREATE TABLE IF NOT EXISTS CHAPTERS (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE       VARCHAR(255),
    ORDER_INDEX INTEGER,
    SUMMARY     CLOB,
    BOOK_ID     BIGINT,
    PART_ID     BIGINT,
    CONSTRAINT FKED84IWJ3KFAGV35ULS80TXKJ4 FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(ID),
    CONSTRAINT FKP18XKTYBOCMDW2OYS6GD46FVT FOREIGN KEY (PART_ID) REFERENCES PARTS(ID)
);

CREATE TABLE IF NOT EXISTS KEY_IDEAS (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENT     VARCHAR(3000),
    EXAMPLE     VARCHAR(3000),
    TAGS        VARCHAR(500),
    HIGHLIGHTED BOOLEAN DEFAULT FALSE NOT NULL,
    ORDER_INDEX INTEGER,
    CHAPTER_ID  BIGINT,
    CONSTRAINT FKK55VE20CSJ6UL80Q9N71GK782 FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS(ID)
);

CREATE TABLE IF NOT EXISTS EXCERPTS (
    ID          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CONTENT     CLOB,
    NOTE        VARCHAR(1000),
    SOURCE      VARCHAR(300),
    ORDER_INDEX INTEGER,
    HIGHLIGHTED BOOLEAN DEFAULT FALSE NOT NULL,
    CHAPTER_ID  BIGINT,
    CONSTRAINT FKJ9XCMQVXY1OELUT23IK6IUOO0 FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS(ID)
);

-- V1 replaces this FK with FK_BOOK_REVIEWS_BOOK, exactly as on legacy databases.
CREATE TABLE IF NOT EXISTS BOOK_REVIEWS (
    ID         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TITLE      VARCHAR(255),
    CONTENT    CLOB,
    UPDATED_AT DATE,
    BOOK_ID    BIGINT NOT NULL,
    CONSTRAINT FKCM2SHIVX19SPBG0FLC47MCRS1 FOREIGN KEY (BOOK_ID) REFERENCES BOOKS(ID)
);

CREATE TABLE IF NOT EXISTS CHAPTER_IMAGES (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FILENAME      VARCHAR(255),
    ORIGINAL_NAME VARCHAR(255),
    CONTENT_TYPE  VARCHAR(255),
    ORDER_INDEX   INTEGER,
    CHAPTER_ID    BIGINT,
    CONSTRAINT FKMBMEFDUVSWWVGJR1R2NAAT4YQ FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS(ID)
);
