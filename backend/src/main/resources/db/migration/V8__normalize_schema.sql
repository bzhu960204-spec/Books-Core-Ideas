-- V8: One canonical schema for every database (DB-01).
--
-- Until now the schema had two sources: databases created before Flyway were
-- shaped by Hibernate (ddl-auto=update), new ones by V0..V7. They drifted apart
-- (constraint names, STRUCTURE_TYPE length, defaults, nullability). From here on
-- Flyway is the only source and Hibernate just validates. This migration brings
-- both shapes to the same result:
--   * every FK / unique constraint / index gets a deterministic name
--     (FK_<table>_<target>, UK_<table>_<columns>, IDX_<table>_<column>);
--   * FK columns get a named index created before the FK, so H2 reuses it
--     instead of adding a system-named duplicate;
--   * column types follow the existing (legacy) database; flags become NOT NULL.
-- FK behaviour is unchanged here (no ON DELETE action); DB-02 changes it in V9.
--
-- H2 commits each DDL statement on its own, so a failure half-way would leave a
-- partly migrated database. The guards below therefore run first and abort
-- before anything is changed if the database is not in a shape this script knows.
-- Flyway logs each SELECT's (empty) result under its column name, hence the aliases.

-- ---- Guards: fail (data conversion error carrying the message) on unknown shapes
SELECT CAST('V8 aborted: unexpected constraint ' || TABLE_NAME || '.' || CONSTRAINT_NAME AS INT) AS V8_CHECK_CONSTRAINT_NAMES
FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
WHERE TABLE_SCHEMA = 'PUBLIC'
  AND CONSTRAINT_TYPE IN ('FOREIGN KEY', 'UNIQUE')
  AND CONSTRAINT_NAME NOT IN (
      -- Hibernate-generated names (legacy databases and V0)
      'FKM12UEOT8L288S8PIHP2F3SNJJ', 'FKED84IWJ3KFAGV35ULS80TXKJ4', 'FKP18XKTYBOCMDW2OYS6GD46FVT',
      'FKK55VE20CSJ6UL80Q9N71GK782', 'FKJ9XCMQVXY1OELUT23IK6IUOO0', 'FKMBMEFDUVSWWVGJR1R2NAAT4YQ',
      'FKCM2SHIVX19SPBG0FLC47MCRS1', 'FK593SYKW9RFSUS4FF0WQGJRTJH', 'UK3P1VGCBH1JB14598SAHGMWM9T',
      -- names from V1..V7
      'FK_BOOK_REVIEWS_BOOK', 'FK_CHAPTER_EXPLANATION_CHAPTER',
      'FK_READING_BOOKMARK_BOOK', 'FK_READING_BOOKMARK_CHAPTER',
      'FK_EXPL_MARK_BOOK', 'FK_EXPL_MARK_CHAPTER', 'UK_BOOK_COLLECTION_ITEMS')
  -- V3 declares UNIQUE inline, so on V0..V7 databases H2 picks the name
  AND NOT (TABLE_NAME = 'CHAPTER_EXPLANATIONS' AND CONSTRAINT_TYPE = 'UNIQUE');

SELECT CAST('V8 aborted: CHAPTER_EXPLANATIONS has ' || N || ' unique constraints' AS INT) AS V8_CHECK_EXPLANATION_UNIQUE
FROM (SELECT COUNT(*) AS N
      FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
      WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = 'CHAPTER_EXPLANATIONS' AND CONSTRAINT_TYPE = 'UNIQUE')
WHERE N <> 1;

SELECT CAST('V8 aborted: unexpected index ' || TABLE_NAME || '.' || INDEX_NAME AS INT) AS V8_CHECK_INDEX_NAMES
FROM INFORMATION_SCHEMA.INDEXES
WHERE TABLE_SCHEMA = 'PUBLIC'
  AND IS_GENERATED = FALSE
  AND TABLE_NAME <> 'flyway_schema_history'
  AND INDEX_NAME NOT IN ('IDX_BCI_COLLECTION_ID', 'IDX_BCI_BOOK_ID', 'IDX_READING_BOOKMARK_BOOK',
                         'IDX_EXPL_MARK_BOOK', 'IDX_EXPL_MARK_CHAPTER');

-- ---- 1. Drop foreign keys (both name variants; their system indexes go with them)
ALTER TABLE PARTS                DROP CONSTRAINT IF EXISTS FKM12UEOT8L288S8PIHP2F3SNJJ;
ALTER TABLE CHAPTERS             DROP CONSTRAINT IF EXISTS FKED84IWJ3KFAGV35ULS80TXKJ4;
ALTER TABLE CHAPTERS             DROP CONSTRAINT IF EXISTS FKP18XKTYBOCMDW2OYS6GD46FVT;
ALTER TABLE KEY_IDEAS            DROP CONSTRAINT IF EXISTS FKK55VE20CSJ6UL80Q9N71GK782;
ALTER TABLE EXCERPTS             DROP CONSTRAINT IF EXISTS FKJ9XCMQVXY1OELUT23IK6IUOO0;
ALTER TABLE CHAPTER_IMAGES       DROP CONSTRAINT IF EXISTS FKMBMEFDUVSWWVGJR1R2NAAT4YQ;
ALTER TABLE BOOK_REVIEWS         DROP CONSTRAINT IF EXISTS FKCM2SHIVX19SPBG0FLC47MCRS1;
ALTER TABLE BOOK_REVIEWS         DROP CONSTRAINT IF EXISTS FK_BOOK_REVIEWS_BOOK;
ALTER TABLE CHAPTER_EXPLANATIONS DROP CONSTRAINT IF EXISTS FK593SYKW9RFSUS4FF0WQGJRTJH;
ALTER TABLE CHAPTER_EXPLANATIONS DROP CONSTRAINT IF EXISTS FK_CHAPTER_EXPLANATION_CHAPTER;
ALTER TABLE READING_BOOKMARKS    DROP CONSTRAINT IF EXISTS FK_READING_BOOKMARK_BOOK;
ALTER TABLE READING_BOOKMARKS    DROP CONSTRAINT IF EXISTS FK_READING_BOOKMARK_CHAPTER;
ALTER TABLE EXPLANATION_MARKS    DROP CONSTRAINT IF EXISTS FK_EXPL_MARK_BOOK;
ALTER TABLE EXPLANATION_MARKS    DROP CONSTRAINT IF EXISTS FK_EXPL_MARK_CHAPTER;

-- ---- 2. Unique constraints: replace the variably named one, rename the other
EXECUTE IMMEDIATE (
    SELECT 'ALTER TABLE CHAPTER_EXPLANATIONS DROP CONSTRAINT "' || CONSTRAINT_NAME || '"'
    FROM INFORMATION_SCHEMA.TABLE_CONSTRAINTS
    WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = 'CHAPTER_EXPLANATIONS' AND CONSTRAINT_TYPE = 'UNIQUE');
ALTER TABLE CHAPTER_EXPLANATIONS ADD CONSTRAINT UK_CHAPTER_EXPLANATIONS_CHAPTER UNIQUE (CHAPTER_ID);
ALTER TABLE BOOK_COLLECTION_ITEMS RENAME CONSTRAINT UK_BOOK_COLLECTION_ITEMS TO UK_BOOK_COLLECTION_ITEMS_COLLECTION_BOOK;

-- ---- 3. Columns: legacy types, defaults everywhere, flags NOT NULL
UPDATE BOOKS SET STRUCTURE_TYPE = 'CHAPTERS' WHERE STRUCTURE_TYPE IS NULL;
ALTER TABLE BOOKS ALTER COLUMN STRUCTURE_TYPE SET DATA TYPE VARCHAR(255);
ALTER TABLE BOOKS ALTER COLUMN STRUCTURE_TYPE SET DEFAULT 'CHAPTERS';
ALTER TABLE BOOKS ALTER COLUMN STRUCTURE_TYPE SET NOT NULL;

UPDATE BOOKS SET CHAPTER_IMAGES_ENABLED = FALSE WHERE CHAPTER_IMAGES_ENABLED IS NULL;
ALTER TABLE BOOKS ALTER COLUMN CHAPTER_IMAGES_ENABLED SET DEFAULT FALSE;
ALTER TABLE BOOKS ALTER COLUMN CHAPTER_IMAGES_ENABLED SET NOT NULL;

UPDATE KEY_IDEAS SET HIGHLIGHTED = FALSE WHERE HIGHLIGHTED IS NULL;
ALTER TABLE KEY_IDEAS ALTER COLUMN HIGHLIGHTED SET DEFAULT FALSE;
ALTER TABLE KEY_IDEAS ALTER COLUMN HIGHLIGHTED SET NOT NULL;

UPDATE EXCERPTS SET HIGHLIGHTED = FALSE WHERE HIGHLIGHTED IS NULL;
ALTER TABLE EXCERPTS ALTER COLUMN HIGHLIGHTED SET DEFAULT FALSE;
ALTER TABLE EXCERPTS ALTER COLUMN HIGHLIGHTED SET NOT NULL;

-- ---- 4. Named indexes on every FK column (before the FKs, so they are reused)
ALTER INDEX IDX_BCI_COLLECTION_ID     RENAME TO IDX_BOOK_COLLECTION_ITEMS_COLLECTION;
ALTER INDEX IDX_BCI_BOOK_ID           RENAME TO IDX_BOOK_COLLECTION_ITEMS_BOOK;
ALTER INDEX IDX_READING_BOOKMARK_BOOK RENAME TO IDX_READING_BOOKMARKS_BOOK;
ALTER INDEX IDX_EXPL_MARK_BOOK        RENAME TO IDX_EXPLANATION_MARKS_BOOK;
ALTER INDEX IDX_EXPL_MARK_CHAPTER     RENAME TO IDX_EXPLANATION_MARKS_CHAPTER;

CREATE INDEX IDX_PARTS_BOOK                 ON PARTS (BOOK_ID);
CREATE INDEX IDX_CHAPTERS_BOOK              ON CHAPTERS (BOOK_ID);
CREATE INDEX IDX_CHAPTERS_PART              ON CHAPTERS (PART_ID);
CREATE INDEX IDX_KEY_IDEAS_CHAPTER          ON KEY_IDEAS (CHAPTER_ID);
CREATE INDEX IDX_EXCERPTS_CHAPTER           ON EXCERPTS (CHAPTER_ID);
CREATE INDEX IDX_CHAPTER_IMAGES_CHAPTER     ON CHAPTER_IMAGES (CHAPTER_ID);
CREATE INDEX IDX_BOOK_REVIEWS_BOOK          ON BOOK_REVIEWS (BOOK_ID);
CREATE INDEX IDX_READING_BOOKMARKS_CHAPTER  ON READING_BOOKMARKS (CHAPTER_ID);

-- ---- 5. Re-add the foreign keys under deterministic names (same behaviour as before)
ALTER TABLE PARTS                ADD CONSTRAINT FK_PARTS_BOOK                   FOREIGN KEY (BOOK_ID)    REFERENCES BOOKS (ID);
ALTER TABLE CHAPTERS             ADD CONSTRAINT FK_CHAPTERS_BOOK                FOREIGN KEY (BOOK_ID)    REFERENCES BOOKS (ID);
ALTER TABLE CHAPTERS             ADD CONSTRAINT FK_CHAPTERS_PART                FOREIGN KEY (PART_ID)    REFERENCES PARTS (ID);
ALTER TABLE KEY_IDEAS            ADD CONSTRAINT FK_KEY_IDEAS_CHAPTER            FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID);
ALTER TABLE EXCERPTS             ADD CONSTRAINT FK_EXCERPTS_CHAPTER             FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID);
ALTER TABLE CHAPTER_IMAGES       ADD CONSTRAINT FK_CHAPTER_IMAGES_CHAPTER       FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID);
ALTER TABLE BOOK_REVIEWS         ADD CONSTRAINT FK_BOOK_REVIEWS_BOOK            FOREIGN KEY (BOOK_ID)    REFERENCES BOOKS (ID);
ALTER TABLE CHAPTER_EXPLANATIONS ADD CONSTRAINT FK_CHAPTER_EXPLANATIONS_CHAPTER FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID);
ALTER TABLE READING_BOOKMARKS    ADD CONSTRAINT FK_READING_BOOKMARKS_BOOK       FOREIGN KEY (BOOK_ID)    REFERENCES BOOKS (ID);
ALTER TABLE READING_BOOKMARKS    ADD CONSTRAINT FK_READING_BOOKMARKS_CHAPTER    FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID);
ALTER TABLE EXPLANATION_MARKS    ADD CONSTRAINT FK_EXPLANATION_MARKS_BOOK       FOREIGN KEY (BOOK_ID)    REFERENCES BOOKS (ID);
ALTER TABLE EXPLANATION_MARKS    ADD CONSTRAINT FK_EXPLANATION_MARKS_CHAPTER    FOREIGN KEY (CHAPTER_ID) REFERENCES CHAPTERS (ID);
