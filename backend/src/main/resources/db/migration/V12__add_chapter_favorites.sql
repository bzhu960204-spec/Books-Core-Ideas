-- V12: Favorite chapters.
--
-- The reader stars a chapter whose explanation is worth re-reading; the Favorite
-- Chapters page lists them across all books. At most one row per chapter, with an
-- optional note on why it is worth coming back to.
-- BOOK_ID sits next to CHAPTER_ID for filtering by book; as for READING_BOOKMARKS and
-- EXPLANATION_MARKS (V9), a composite FK keeps it equal to the chapter's book, and
-- deleting the chapter (or its book) deletes the favorite.

CREATE TABLE CHAPTER_FAVORITES (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BOOK_ID BIGINT NOT NULL,
    CHAPTER_ID BIGINT NOT NULL,
    NOTE CHARACTER VARYING(500),
    CREATED_AT TIMESTAMP(6),
    CONSTRAINT UK_CHAPTER_FAVORITES_CHAPTER UNIQUE (CHAPTER_ID)
);

CREATE INDEX IDX_CHAPTER_FAVORITES_BOOK ON CHAPTER_FAVORITES (BOOK_ID);
CREATE INDEX IDX_CHAPTER_FAVORITES_CHAPTER_BOOK ON CHAPTER_FAVORITES (CHAPTER_ID, BOOK_ID);

ALTER TABLE CHAPTER_FAVORITES ADD CONSTRAINT FK_CHAPTER_FAVORITES_CHAPTER
    FOREIGN KEY (CHAPTER_ID, BOOK_ID) REFERENCES CHAPTERS (ID, BOOK_ID) ON DELETE CASCADE;
